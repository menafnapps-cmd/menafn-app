  insertArt({
    required int id,
    required String imagePath,
    required String newsTitle,
    required String link,
  }) async {
    var result = await database.rawQuery(
      'SELECT count(newsId)  FROM saveArt1 WHERE  newsId = $id',
    );
    int count = result[0]['count(newsId)'] as int;
    print('id:$id');
    if (count == 0) {
      await database.transaction((txn) async {
        txn.rawInsert(
            'INSERT INTO saveArt1 (newsId, imagePath, newsTitle, link) VALUES("$id", "$imagePath", "$newsTitle","$link")');
      }).then((value) {
        select = true;
        getDataFromDatabase(database);
        emit(getDataFromDatabaseState());
        print('insert row done $id');
      }).catchError((error) {
        print('not insert $error');
      });
    } else {
      await database
          .rawDelete('DELETE FROM saveArt1 WHERE newsId = $id')
